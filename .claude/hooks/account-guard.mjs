#!/usr/bin/env node
// account-guard.mjs: the account guard. A PreToolUse hook on every Meta Ads MCP call (and a PostToolUse hook
// on the same calls) that keeps this harness inside the ONE ad account its config names.
//
// Why: the harness is installed per company. One Meta login can see several ad accounts (an old account, an
// agency's other clients, a Page's second account). A write to the wrong one is the costliest mistake a
// marketing harness can make, and no rule in a prompt can guarantee it never happens. This hook can.
//
// What it does (PreToolUse, tool names mcp__meta-ads__ads_*):
//   1. Reads the allowed account id from config/accounts.md (`meta_ad_account_id`), with .env's
//      META_AD_ACCOUNT_ID as the fallback (that key only; the token line is never read).
//   2. Every call that carries an account id (ad_account_id, account_id, act_id, or any string that looks
//      like act_<digits>) is refused when that id is not the allowed one. Reads included: a read of another
//      account is how a wrong-account build starts.
//   3. Every WRITE call (create, update, activate, delete, upload, audience, pixel, catalog, experiment,
//      boost) whose input names ad objects by id (campaign_id, adset_id, ad_id, creative_id, object_id,
//      entity_id, entity_ids, audience_id, ...) is refused when an id is unknown: an object id is known when
//      a Meta read or create in THIS harness folder returned it (the PostToolUse recorder below keeps them in
//      memory/state/known-objects.json) or when it is written in the vault (memory/, plans/, reports/,
//      config/, checklist.md). An id nobody has seen is not ours to change.
//   4. `ads_get_ad_accounts`, `ads_get_user_pages`, `ads_get_pages_for_business`, `ads_get_help_article`,
//      `ads_get_field_context` and `ads_library_search` carry no account and always pass.
//   Refusal = exit code 2 with the reason on stderr (Claude Code blocks the call and shows the reason).
//   Before /setup (no account in config and none in .env) every Meta call passes, so the wizard's first
//   live reads can run; the wizard writes the id and the guard is live from then on.
// What it does (PostToolUse, same tools): records every object id the response carries under the allowed
//   account in memory/state/known-objects.json (ids only, no names, no metrics; the file is git-ignored and
//   regenerated by use; a missing file is fine). It also records the account id a read came back with.
// Hook contract (https://code.claude.com/docs/en/hooks): stdin JSON with hook_event_name, tool_name,
//   tool_input (PreToolUse) and tool_response (PostToolUse); CLAUDE_PROJECT_DIR is the harness folder.
//   The hook always exits 0 when it cannot decide (no input, no config, a parse error): it never blocks by
//   accident, it blocks only on evidence.
// Codex (--codex, the command in .codex/hooks.json): Codex cannot take a tool away from one sub-agent, so with
//   --codex the guard also refuses every call that turns something on, deletes, or touches money, unless a go ticket
//   names its ids: ads_activate_entity, every delete, ads_update_entity setting a status of ACTIVE, DELETED or
//   ARCHIVED or any budget, bid, spend cap or end time, ads_boost_ig_post and experiment creates. The main session
//   writes the ticket in the turn of the Owner's go:
//     node .claude/hooks/account-guard.mjs --ticket --go "<the Owner's words>" --ids <id,id,...> [--minutes 30]
//   (memory/state/go-ticket.json, git-ignored; at most 60 minutes; --ticket --clear removes it). Codex sends the same
//   stdin fields and takes exit code 2 with the reason on stderr (learn.chatgpt.com/docs/hooks, read 2026-10-30).
// Dry check from the harness folder:
//   echo '{"hook_event_name":"PreToolUse","tool_name":"mcp__meta-ads__ads_create_campaign","tool_input":{"ad_account_id":"1000000000000001"}}' | node .claude/hooks/account-guard.mjs ; echo exit $?
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ACCOUNT_KEYS = new Set(['ad_account_id', 'account_id', 'act_id', 'adaccount_id', 'ad_account']);
const OBJECT_KEYS = new Set([
  'campaign_id', 'campaign_ids', 'adset_id', 'adset_ids', 'ad_set_id', 'ad_set_ids', 'ad_id', 'ad_ids',
  'creative_id', 'creative_ids', 'object_id', 'object_ids', 'entity_id', 'entity_ids', 'audience_id',
  'custom_audience_id', 'origin_audience_id', 'pixel_id', 'dataset_id', 'catalog_id', 'product_feed_id',
  'product_set_id', 'product_id', 'test_id', 'study_id', 'image_hash', 'image_hashes', 'video_id', 'video_ids',
]);
// Tools that never carry an account and always pass (discovery reads and documentation).
const ALWAYS_PASS = new Set([
  'ads_get_ad_accounts', 'ads_get_user_pages', 'ads_get_pages_for_business', 'ads_get_help_article',
  'ads_get_field_context', 'ads_library_search', 'ads_get_ig_accounts', 'ads_catalog_get_businesses',
]);
// With --codex: the calls that need a go ticket (see the header).
const GO_TOOL_RE = /^ads_(activate_entity|boost_ig_post|experiment_.*_create_test)$|delete/;
const MONEY_KEY_RE = /budget|spend_cap|bid_amount|bid_strategy|end_time|stop_time/i;
const WRITE_RE = /^ads_(create_|update_|activate_|delete_|creative_(upload|update|delete)|catalog_(create|update|delete|product_|event_source_(connect|disconnect))|experiment_.*_(create|update)_|pixel_(event|parameter)_(create|update|delete)|boost_)/;

export function readStdin() {
  try { return fs.readFileSync(0, 'utf8'); } catch { return ''; }
}

export function projectDir(input) {
  const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
  for (const s of [process.env.CLAUDE_PROJECT_DIR, input && input.cwd, process.cwd(), here]) {
    if (!s) continue;
    let dir = path.resolve(s);
    for (let i = 0; i < 8; i++) {
      if (fs.existsSync(path.join(dir, 'config', 'accounts.md')) || fs.existsSync(path.join(dir, 'memory', 'README.md'))) return dir;
      const up = path.dirname(dir);
      if (up === dir) break;
      dir = up;
    }
  }
  return here;
}

const digitsOnly = (v) => String(v || '').trim().replace(/^act_/i, '');

// The allowed account: config/accounts.md's meta_ad_account_id row, else .env's META_AD_ACCOUNT_ID (that key only).
export function allowedAccount(root) {
  try {
    const md = fs.readFileSync(path.join(root, 'config', 'accounts.md'), 'utf8');
    const m = /\|\s*`meta_ad_account_id`\s*\|\s*`?(?:act_)?(\d{6,})`?\s*\|/i.exec(md);
    if (m) return m[1];
  } catch { /* no config yet */ }
  try {
    for (const raw of fs.readFileSync(path.join(root, '.env'), 'utf8').split(/\r?\n/)) {
      const m = /^(?:export\s+)?META_AD_ACCOUNT_ID\s*=\s*["']?(?:act_)?(\d{6,})["']?\s*$/.exec(raw.trim());
      if (m) return m[1];
    }
  } catch { /* no .env */ }
  return null;
}

// Every account id and every object id the tool input carries (keys first, then act_<digits> strings anywhere).
export function collectIds(obj) {
  const accounts = new Set();
  const objects = new Set();
  const walk = (v, key) => {
    if (v == null) return;
    if (Array.isArray(v)) { for (const x of v) walk(x, key); return; }
    if (typeof v === 'object') { for (const [k, x] of Object.entries(v)) walk(x, k); return; }
    if (typeof v !== 'string' && typeof v !== 'number') return;
    const s = String(v).trim();
    const actm = /^act_(\d{6,})$/i.exec(s);
    if (ACCOUNT_KEYS.has(key) && /^(act_)?\d{6,}$/i.test(s)) accounts.add(digitsOnly(s));
    else if (actm) accounts.add(actm[1]);
    else if (OBJECT_KEYS.has(key) && /^\d{6,}$/.test(s)) objects.add(s);
    else if (key === 'image_hash' || key === 'image_hashes') objects.add(s);
    // Nested JSON strings (targeting specs, rules) are parsed once so an account inside them is seen too.
    if (typeof v === 'string' && s.startsWith('{') && s.length < 200000) {
      try { walk(JSON.parse(s), key); } catch { /* not JSON */ }
    }
  };
  walk(obj, '');
  return { accounts: [...accounts], objects: [...objects] };
}

export function knownFile(root) { return path.join(root, 'memory', 'state', 'known-objects.json'); }

export function loadKnown(root) {
  try {
    const j = JSON.parse(fs.readFileSync(knownFile(root), 'utf8'));
    return { account: j.account || null, ids: new Set(Array.isArray(j.ids) ? j.ids : []) };
  } catch { return { account: null, ids: new Set() }; }
}

export function saveKnown(root, known) {
  try {
    fs.mkdirSync(path.dirname(knownFile(root)), { recursive: true });
    const ids = [...known.ids].slice(-5000);
    fs.writeFileSync(knownFile(root), JSON.stringify({ account: known.account, updated: new Date().toISOString(), ids }, null, 0) + '\n');
  } catch { /* never block */ }
}

// Is the id written anywhere in the vault, the plans, the reports, the config or the checklist?
export function idInVault(root, id) {
  const roots = ['memory', 'plans', 'reports', 'config', 'checklist.md'];
  const stack = roots.map((r) => path.join(root, r));
  let budget = 4000; // files
  while (stack.length && budget-- > 0) {
    const p = stack.pop();
    let st;
    try { st = fs.statSync(p); } catch { continue; }
    if (st.isDirectory()) {
      if (/[\\/](archive|node_modules|\.git)$/.test(p)) continue;
      for (const n of fs.readdirSync(p)) stack.push(path.join(p, n));
    } else if (/\.(md|json|txt|base)$/i.test(p) && st.size < 2_000_000) {
      try { if (fs.readFileSync(p, 'utf8').includes(id)) return true; } catch { /* skip */ }
    }
  }
  return false;
}

// Every digit string of 6+ in a tool response that sits under an id-like key.
export function idsInResponse(resp) {
  const out = new Set();
  const walk = (v, key) => {
    if (v == null) return;
    if (Array.isArray(v)) { for (const x of v) walk(x, key); return; }
    if (typeof v === 'object') { for (const [k, x] of Object.entries(v)) walk(x, k); return; }
    if (typeof v === 'string' && v.startsWith('{') && v.length < 2_000_000) {
      try { walk(JSON.parse(v), key); return; } catch { /* text */ }
    }
    if (typeof v === 'string' && /"id"\s*:\s*"\d{6,}"/.test(v)) {
      for (const m of v.matchAll(/"(?:id|campaign_id|adset_id|ad_id|creative_id|audience_id|image_hash|video_id)"\s*:\s*"([0-9a-f]{6,})"/gi)) out.add(m[1]);
      return;
    }
    const s = String(v).trim();
    if (/^(id|campaign_id|adset_id|ad_id|creative_id|audience_id|dataset_id|pixel_id|video_id|image_hash|hash)$/.test(key) && /^[0-9a-f]{6,}$/i.test(s)) out.add(s.replace(/^act_/i, ''));
  };
  walk(resp, '');
  return [...out];
}

export function ticketFile(root) { return path.join(root, 'memory', 'state', 'go-ticket.json'); }

/** The live go ticket ({ ids, words, expires }) or null when there is none or it expired. */
export function loadTicket(root, now = Date.now()) {
  try {
    const t = JSON.parse(fs.readFileSync(ticketFile(root), 'utf8'));
    if (!Array.isArray(t.ids) || !t.expires || Date.parse(t.expires) <= now) return null;
    return t;
  } catch { return null; }
}

export function writeTicket(root, { go, ids, minutes = 30 }, now = Date.now()) {
  const words = String(go || '').trim();
  const list = String(ids || '').split(/[\s,]+/).map((x) => x.trim().replace(/^act_/i, '')).filter(Boolean);
  if (!words) return { ok: false, reason: 'a go ticket needs the Owner\'s words: --go "<words>"' };
  if (!list.length || list.some((x) => !/^\d{6,}$/.test(x))) return { ok: false, reason: 'a go ticket needs the ids it covers: --ids <digits,digits,...>' };
  const mins = Math.min(60, Math.max(1, Number(minutes) || 30));
  const t = { created: new Date(now).toISOString(), expires: new Date(now + mins * 60000).toISOString(), words, ids: list };
  fs.mkdirSync(path.dirname(ticketFile(root)), { recursive: true });
  fs.writeFileSync(ticketFile(root), JSON.stringify(t, null, 2) + '\n');
  return { ok: true, ticket: t, minutes: mins };
}

/** Does this call turn something on, delete, or touch money (the calls that need a go ticket under --codex)? */
export function needsGo(short, toolInput) {
  if (GO_TOOL_RE.test(short)) return true;
  if (short !== 'ads_update_entity') return false;
  let hit = false;
  const walk = (v, key) => {
    if (hit || v == null) return;
    if (Array.isArray(v)) { for (const x of v) walk(x, key); return; }
    if (typeof v === 'object') { for (const [k, x] of Object.entries(v)) { if (MONEY_KEY_RE.test(k)) hit = true; walk(x, k); } return; }
    if (typeof v === 'string' && v.trim().startsWith('{')) { try { walk(JSON.parse(v), key); return; } catch { /* text */ } }
    if (/status$/i.test(key) && /^(ACTIVE|DELETED|ARCHIVED)$/i.test(String(v).trim())) hit = true;
  };
  walk(toolInput || {}, '');
  return hit;
}

export function decide(input, root, { codex = false, now = Date.now() } = {}) {
  const tool = String(input.tool_name || '');
  if (!tool.startsWith('mcp__meta-ads__')) return { ok: true };
  const short = tool.slice('mcp__meta-ads__'.length);
  if (ALWAYS_PASS.has(short)) return { ok: true };
  const allowed = allowedAccount(root);
  if (!allowed) return { ok: true, note: 'no account in config yet' };
  const { accounts, objects } = collectIds(input.tool_input || {});
  const wrong = accounts.filter((a) => a !== allowed);
  if (wrong.length) {
    return {
      ok: false,
      reason: `account guard: ${short} names ad account ${wrong.join(', ')} but this harness is bound to act_${allowed} (config/accounts.md, meta_ad_account_id). Nothing was sent. If the company's account changed, the Owner updates config/accounts.md (and .env) first.`,
    };
  }
  if (!WRITE_RE.test(short)) return { ok: true };
  if (codex && needsGo(short, input.tool_input)) {
    const t = loadTicket(root, now);
    const missing = t ? objects.filter((id) => !t.ids.includes(id)) : objects;
    if (!t || missing.length) {
      return {
        ok: false,
        reason: `account guard (Codex): ${short} turns something on, deletes or touches money, and ${t ? `the go ticket does not name ${missing.join(', ')}` : 'there is no live go ticket'}. Only the main session, in the turn of the Owner's go, runs: node .claude/hooks/account-guard.mjs --ticket --go "<the Owner's words>" --ids <the ids>. A sub-agent never does. Nothing was sent.`,
      };
    }
  }
  if (!objects.length) return { ok: true };
  const known = loadKnown(root);
  const unknown = objects.filter((id) => !known.ids.has(id) && !idInVault(root, id));
  if (unknown.length) {
    return {
      ok: false,
      reason: `account guard: ${short} would write to object(s) ${unknown.join(', ')} that no read or create in this harness has returned and that no vault note, plan, report or config names. Read the object first with ads_get_ad_entities under act_${allowed} (the guard records what a read returns), or record its id in the campaign note, then retry. Nothing was sent.`,
    };
  }
  return { ok: true };
}

export function record(input, root) {
  const tool = String(input.tool_name || '');
  if (!tool.startsWith('mcp__meta-ads__')) return;
  const allowed = allowedAccount(root);
  if (!allowed) return;
  const { accounts } = collectIds(input.tool_input || {});
  // Only responses to calls made under the allowed account teach the guard new ids.
  if (accounts.some((a) => a !== allowed)) return;
  const ids = idsInResponse(input.tool_response);
  if (!ids.length) return;
  const known = loadKnown(root);
  known.account = allowed;
  for (const id of ids) known.ids.add(id);
  saveKnown(root, known);
}

function ticketCli(argv) {
  const val = (k) => { const i = argv.indexOf(k); return i !== -1 ? argv[i + 1] : undefined; };
  const root = projectDir({ cwd: process.cwd() });
  if (argv.includes('--clear')) { fs.rmSync(ticketFile(root), { force: true }); process.stdout.write('go ticket: cleared\n'); process.exit(0); }
  const r = writeTicket(root, { go: val('--go'), ids: val('--ids'), minutes: val('--minutes') });
  if (!r.ok) { process.stderr.write(`go ticket: ${r.reason}\n`); process.exit(2); }
  process.stdout.write(`go ticket: ${r.ticket.ids.length} id(s) for ${r.minutes} minutes (until ${r.ticket.expires}); write the go-log row as usual\n`);
  process.exit(0);
}

function main() {
  const argv = process.argv.slice(2);
  if (argv.includes('--ticket')) ticketCli(argv);
  let input = {};
  try { input = JSON.parse(readStdin() || '{}'); } catch { input = {}; }
  const root = projectDir(input);
  const event = String(input.hook_event_name || '');
  try {
    if (event === 'PostToolUse') { record(input, root); process.exit(0); }
    const d = decide(input, root, { codex: argv.includes('--codex') });
    if (!d.ok) { process.stderr.write(d.reason + '\n'); process.exit(2); }
  } catch (e) {
    // Undecidable: never block by accident.
    process.stderr.write(`account guard: skipped (${(e && e.message) || e})\n`);
  }
  process.exit(0);
}

const isEntry = (() => {
  try { return process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url); } catch { return false; }
})();
if (isEntry) main();
