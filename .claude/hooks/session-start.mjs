#!/usr/bin/env node
// SessionStart hook: injects memory/HOT.md (the vault's hot HOT, without its frontmatter) into every new
// session as context. Node 20+, no dependencies.
// Hook contract (https://code.claude.com/docs/en/hooks, read 2026-10-26):
//   stdin  JSON with the common fields session_id, transcript_path, cwd, permission_mode, hook_event_name
//          ("SessionStart") and the event's own `source` ("startup" | "resume" | "clear" | "compact" | "fork"),
//          optional `model`, `agent_type`, `session_title`.
//   stdout {"hookSpecificOutput":{"hookEventName":"SessionStart","additionalContext":"<text>"}}: the
//          additionalContext string is added to Claude's context before the first prompt.
//   env    CLAUDE_PROJECT_DIR, the project root where the session started.
// The vault root is the first of CLAUDE_PROJECT_DIR, the input's cwd, process.cwd() and this file's
// grandparent folder that holds memory/HOT.md (walking up). No HOT: prints nothing, exits 0. Never fails.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

function readStdin() {
  try { return fs.readFileSync(0, 'utf8'); } catch { return ''; }
}

function findHOT(starts) {
  for (const s of starts) {
    if (!s) continue;
    let dir = path.resolve(s);
    for (let i = 0; i < 8; i++) {
      const hot = path.join(dir, 'memory', 'HOT.md');
      if (fs.existsSync(hot)) return hot;
      const up = path.dirname(dir);
      if (up === dir) break;
      dir = up;
    }
  }
  return null;
}

try {
  let input = {};
  try { input = JSON.parse(readStdin() || '{}'); } catch { input = {}; }
  const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
  const hot = findHOT([process.env.CLAUDE_PROJECT_DIR, input.cwd, process.cwd(), here]);
  if (hot) {
    const text = fs.readFileSync(hot, 'utf8').replace(/^﻿/, '').replace(/\r\n?/g, '\n');
    const m = /^---\n[\s\S]*?\n---[ \t]*\n/.exec(text);
    const body = (m ? text.slice(m[0].length) : text).trim();
    if (body) {
      const additionalContext = `memory/HOT.md (the vault's hot HOT, generated by memory/tools/build-hot.mjs):\n\n${body}`;
      process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: 'SessionStart', additionalContext } }));
    }
  }
} catch {
  // never block a session start
}
process.exit(0);
