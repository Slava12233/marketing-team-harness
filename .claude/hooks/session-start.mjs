#!/usr/bin/env node
// SessionStart and SubagentStart hook: injects memory/HOT.md (without its frontmatter) into every new session
// and every sub-agent as context.
// Hook contract (https://code.claude.com/docs/en/hooks, read 2026-10-26):
//   stdin  JSON with the common fields session_id, transcript_path, cwd, permission_mode, hook_event_name
//          ("SessionStart") and the event's own `source` ("startup" | "resume" | "clear" | "compact" | "fork"),
//          optional `model`, `agent_type`, `session_title`. SubagentStart sends hook_event_name "SubagentStart";
//          both events take hookSpecificOutput.additionalContext ("context only" in the decision table).
//   stdout {"hookSpecificOutput":{"hookEventName":"<the input event>","additionalContext":"<text>"}}: the
//          additionalContext string is added to Claude's context before the first prompt.
//   env    CLAUDE_PROJECT_DIR, the project root where the session started.
// The vault root is CLAUDE_PROJECT_DIR when it is set (walking up to memory/HOT.md); without it, the first of
// the input's cwd, process.cwd() and this file's grandparent folder. No HOT.md: prints nothing, exits 0.
// --codex (the command in .codex/hooks.json, written by memory/tools/codex-sync.mjs): Codex has no @imports, so the
// context also carries the company files CLAUDE.md imports (its @config/*.md lines, in order), each under its path.
// Codex sends the same stdin fields and takes the same hookSpecificOutput.additionalContext
// (learn.chatgpt.com/docs/hooks, read 2026-10-30).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

function readStdin() {
  try { return fs.readFileSync(0, 'utf8'); } catch { return ''; }
}

const clean = (t) => t.replace(/^﻿/, '').replace(/\r\n?/g, '\n');

// The first folder at or above a start that holds `marker`.
function findUp(starts, marker) {
  for (const s of starts) {
    if (!s) continue;
    let dir = path.resolve(s);
    for (let i = 0; i < 8; i++) {
      if (fs.existsSync(path.join(dir, marker))) return dir;
      const up = path.dirname(dir);
      if (up === dir) break;
      dir = up;
    }
  }
  return null;
}

export function findHot(starts) {
  const dir = findUp(starts, path.join('memory', 'HOT.md'));
  return dir ? path.join(dir, 'memory', 'HOT.md') : null;
}

/** The context text: HOT.md's body and, with codex, every file CLAUDE.md imports. Empty when there is nothing. */
export function contextText(starts, { codex = false } = {}) {
  const parts = [];
  const hot = findHot(starts);
  if (hot) {
    const text = clean(fs.readFileSync(hot, 'utf8'));
    const m = /^---\n[\s\S]*?\n---[ \t]*\n/.exec(text);
    const body = (m ? text.slice(m[0].length) : text).trim();
    if (body) parts.push(`memory/HOT.md (the vault's hot note, generated by build-hot.mjs):\n\n${body}`);
  }
  if (codex) {
    const root = hot ? path.dirname(path.dirname(hot)) : findUp(starts, 'CLAUDE.md');
    let claude = '';
    try { claude = clean(fs.readFileSync(path.join(root, 'CLAUDE.md'), 'utf8')); } catch { /* none */ }
    for (const m of claude.matchAll(/^@(\S+\.md)[ \t]*$/gm)) {
      try {
        const t = clean(fs.readFileSync(path.join(root, m[1]), 'utf8')).trim();
        if (t) parts.push(`${m[1]} (imported by CLAUDE.md):\n\n${t}`);
      } catch { /* a missing file is skipped */ }
    }
  }
  return parts.join('\n\n---\n\n');
}

const isMain = (() => { try { return path.resolve(fileURLToPath(import.meta.url)) === path.resolve(process.argv[1] || ''); } catch { return false; } })();
if (isMain) {
  try {
    let input = {};
    try { input = JSON.parse(readStdin() || '{}'); } catch { input = {}; }
    const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
    // Claude Code always sets CLAUDE_PROJECT_DIR for hooks; then only that project is searched.
    const starts = process.env.CLAUDE_PROJECT_DIR ? [process.env.CLAUDE_PROJECT_DIR] : [input.cwd, process.cwd(), here];
    const additionalContext = contextText(starts, { codex: process.argv.includes('--codex') });
    if (additionalContext) {
      const hookEventName = input.hook_event_name === 'SubagentStart' ? 'SubagentStart' : 'SessionStart';
      process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName, additionalContext } }));
    }
  } catch {
    // never block a session start
  }
  process.exit(0);
}
