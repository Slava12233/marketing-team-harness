/** AGENTS.md from CLAUDE.md. */
export function agentsMd(claudeMd) {
  const text = eol(claudeMd);
  const imports = claudeImports(text);
  let body = text;
  if (imports.length) {
    const lines = body.split('\n');
    const first = lines.findIndex(l => /^@\S+\.md[ \t]*$/.test(l));
    const kept = lines.filter(l => !/^@\S+\.md[ \t]*$/.test(l));
    kept.splice(first, 0, `The company's files, imported in Claude, are injected here by the session-start hook (or read by you at the start): ${imports.map(i => `\`${i}\``).join(', ')}.`);
    body = kept.join('\n');
  }
  return PREFACE(imports) + body.replace(/\s*$/, '\n');
}

/** The Codex copy of one SKILL.md, plus an agents/openai.yaml when the skill is explicit-only. */
export function codexSkill(text) {
  const src = eol(text);
  const parts = splitFrontmatter(src);
  if (!parts.hasFm) return { skill: src, openai: null };
  const fm = parseFrontmatter(parts.fmText);
  const description = str(fm.description);
  let fmText = parts.fmText;
  if (description.length > DESCRIPTION_MAX) {
    const lines = fmText.split('\n');
    const i = lines.findIndex(l => /^description:/.test(l));
    let j = i + 1;
    while (j < lines.length && /^\s/.test(lines[j])) j++; // a folded or indented description
    lines.splice(i, j - i, `description: ${JSON.stringify(shortDescription(description))}`);
    fmText = lines.join('\n');
  }
  const explicitOnly = String(fm['disable-model-invocation'] ?? '').trim() === 'true';
  const openai = explicitOnly ? `# ${GENERATED}\npolicy:\n  allow_implicit_invocation: false\n` : null;
  return { skill: `---\n${fmText}\n---\n${parts.body}`, openai };
}

/** The Codex agent file for one .claude/agents/<name>.md. */
export function codexAgent(text, rel) {
  const parts = splitFrontmatter(eol(text));
  const fm = parseFrontmatter(parts.fmText);
  const list = v => (Array.isArray(v) ? v.map(String) : str(v) ? str(v).split(',').map(s => s.trim()).filter(Boolean) : []);
  const name = str(fm.name) || path.basename(rel, '.md');
  const m = MODELS[str(fm.model)] || null;
  const never = list(fm.disallowedTools);
  const skills = list(fm.skills);
  const pre = [
    `You run as the ${name} sub-agent of the marketing harness in Codex. The rulebook is AGENTS.md (CLAUDE.md); "the main session" is the Codex thread that spawned you.`,
    never.length ? `Never call these tools (in Claude they are taken away from you; in Codex this line is the rule): ${never.join(', ')}.` : '',
    skills.length ? `Before you start, read these skills: ${skills.map(s => `.agents/skills/${s}/SKILL.md`).join(', ')}.` : '',
    'Never write a go ticket (account-guard.mjs --ticket) and never pass --go to a tool: the go is the Owner\'s, carried out by the main session.',
  ].filter(Boolean).join('\n');
  return [
    `# ${GENERATED.replace('change the Claude source', `change ${rel}`)}`,
    `name = ${tomlStr(name)}`,
    `description = ${tomlStr(str(fm.description))}`,
    m ? `model = ${tomlStr(m.model)}` : null,
    m ? `model_reasoning_effort = ${tomlStr(m.effort)}` : null,
    `developer_instructions = ${tomlBlock(`${pre}\n\n${parts.body.trim()}\n`)}`,
    '',
  ].filter(l => l !== null).join('\n');
}

/** .codex/config.toml from .mcp.json. */
export function configToml(mcp) {
  const servers = Object.entries((mcp && mcp.mcpServers) || {});
  const out = [
    `# ${GENERATED.replace('change the Claude source', 'change .mcp.json')}`,
    '# Loaded only when the user trusts this project in Codex. Log in to each server with: codex mcp login <name>',
    `project_doc_max_bytes = ${DOC_MAX_BYTES}`,
    'sandbox_mode = "workspace-write"',
    '',
    '[sandbox_workspace_write]',
    '# The Node tools call the Meta Graph API and the Google Ads API.',
    'network_access = true',
    '',
    '[agents]',
    'max_concurrent_threads_per_session = 6',
  ];
  for (const [name, s] of servers) {
    out.push('', `[mcp_servers.${/^[A-Za-z0-9_-]+$/.test(name) ? name : tomlStr(name)}]`);
    if (s.url) { out.push(`url = ${tomlStr(s.url)}`, 'tool_timeout_sec = 180'); }
    if (s.command) {
      out.push(`command = ${tomlStr(s.command)}`);
      if (Array.isArray(s.args)) out.push(`args = [${s.args.map(tomlStr).join(', ')}]`);
    }
  }
  return out.join('\n') + '\n';
}

/** .codex/hooks.json from .claude/settings.json: the same events, each command with --codex. */
export function hooksJson(settings) {
  const hooks = {};
  for (const [event, groups] of Object.entries((settings && settings.hooks) || {})) {
    hooks[event] = groups.map(g => {
      const group = {};
      if (g.matcher && g.matcher !== '*') group.matcher = g.matcher;
      group.hooks = (g.hooks || []).map(h => {
        const command = /--codex\b/.test(h.command) ? h.command : `${h.command} --codex`;
        const out = { type: h.type || 'command', command, commandWindows: command };
        if (h.timeout) out.timeout = h.timeout;
        if (/session-start\.mjs/.test(h.command)) out.additionalContextLimit = CONTEXT_LIMIT;
        return out;
      });
      return group;
    });
  }
  return JSON.stringify({ description: GENERATED.replace('change the Claude source', 'change .claude/settings.json'), hooks }, null, 2) + '\n';
}

function listDir(abs) {
  const out = [];
  const stack = [''];
  while (stack.length) {
    const rel = stack.pop();
    let entries = [];
    try { entries = fs.readdirSync(path.join(abs, rel), { withFileTypes: true }); } catch { continue; }
    for (const e of entries) {
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) stack.push(r); else if (e.isFile()) out.push(r);
    }
  }
  return out.sort();
}

/** Every generated file: relative posix path → string or Buffer. */
export function plan(root) {
  const files = new Map();
  const claude = read(root, 'CLAUDE.md');
  if (claude !== null) files.set('AGENTS.md', agentsMd(claude));
  const skillsDir = path.join(root, '.claude', 'skills');
  let names = [];
  try { names = fs.readdirSync(skillsDir, { withFileTypes: true }).filter(e => e.isDirectory()).map(e => e.name).sort(); } catch { /* none */ }
  for (const n of names) {
    const rels = listDir(path.join(skillsDir, n));
    for (const rel of rels) {
      const out = `.agents/skills/${n}/${rel}`;
      const abs = path.join(skillsDir, n, rel);
      if (rel === 'SKILL.md') {
        const { skill, openai } = codexSkill(fs.readFileSync(abs, 'utf8'));
        files.set(out, skill);
        // A skill that ships its own agents/openai.yaml (a third-party one) keeps it.
        if (openai && !rels.includes('agents/openai.yaml')) files.set(`.agents/skills/${n}/agents/openai.yaml`, openai);
      } else files.set(out, fs.readFileSync(abs));
    }
  }
  let agents = [];
  try { agents = fs.readdirSync(path.join(root, '.claude', 'agents')).filter(f => f.endsWith('.md')).sort(); } catch { /* none */ }
  for (const f of agents) {
    const rel = `.claude/agents/${f}`;
    files.set(`.codex/agents/${path.basename(f, '.md')}.toml`, codexAgent(read(root, rel), rel));
  }
  let mcp = {};
  try { mcp = JSON.parse(read(root, '.mcp.json') || '{}'); } catch { /* none */ }
  files.set('.codex/config.toml', configToml(mcp));
  let settings = {};
  try { settings = JSON.parse(read(root, '.claude/settings.json') || '{}'); } catch { /* none */ }
  files.set('.codex/hooks.json', hooksJson(settings));
  return files;
}

// Line ends never count (a Windows checkout turns LF into CRLF in the copy and in its source alike, or in one only).
const isText = b => !b.includes(0);
const same = (old, want) => {
  if (!Buffer.isBuffer(want)) return eol(old.toString('utf8')) === eol(want);
  if (Buffer.compare(old, want) === 0) return true;
  return isText(old) && isText(want) && eol(old.toString('utf8')) === eol(want.toString('utf8'));
};

/** Compares (and with write, applies) the plan. Returns { stale, extra, written, removed }. */
export function sync(root, { write = false } = {}) {
  const files = plan(root);
  const stale = []; const written = [];
  for (const [rel, want] of files) {
    const abs = path.join(root, rel);
    let old = null;
    try { old = fs.readFileSync(abs); } catch { /* missing */ }
    if (old !== null && same(old, want)) continue;
    stale.push(rel);
    if (write) { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, want); written.push(rel); }
  }
  // Left-overs: generated folders hold only what the plan names (a skill or agent removed from .claude/).
  const extra = []; const removed = [];
  for (const dir of ['.agents/skills', '.codex/agents']) {
    for (const rel of listDir(path.join(root, dir))) {
      const r = toPosix(`${dir}/${rel}`);
      if (files.has(r)) continue;
      extra.push(r);
      if (write) { fs.rmSync(path.join(root, r), { force: true }); removed.push(r); }
    }
  }
  return { stale, extra, written, removed, count: files.size };
}

if (isMain(import.meta.url)) {
  const { flags } = parseFlags();
  const root = findRoot();
  const write = flags.has('write');
  const r = sync(root, { write });
  if (write) {
    console.log(`codex-sync: ${r.written.length} written, ${r.removed.length} removed, ${r.count - r.written.length} unchanged`);
    for (const f of [...r.written, ...r.removed.map(x => `${x} (removed)`)].slice(0, 40)) console.log(`  ${f}`);
  } else if (r.stale.length || r.extra.length) {
    console.log(`codex-sync: the Codex files are out of date (${r.stale.length} stale or missing, ${r.extra.length} left over); run node memory/tools/codex-sync.mjs --write`);
    for (const f of [...r.stale, ...r.extra.map(x => `${x} (left over)`)].slice(0, 20)) console.log(`  ${f}`);
    process.exit(1);
  } else console.log(`codex-sync: the Codex files match the Claude source (${r.count} files)`);
}
